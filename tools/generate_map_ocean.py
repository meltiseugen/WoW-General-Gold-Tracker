"""Generate original detail backdrops from the mask receipt's ocean statistics.

Run after generate_map_art_masks.py. Requires NumPy, SciPy and Pillow.
Only cached Blizzard samples are inputs; no other addon's assets are read.
"""
import argparse
import hashlib
import json
from pathlib import Path

from map_art_ownership import ocean_field
from map_mask_texture import read_texture,save_texture


def generate(receipt, cache, output, index):
    data=json.loads(receipt.read_text())
    output.mkdir(parents=True,exist_ok=True)
    generated={}
    for art,record in sorted(data['paper_sources'].items(),key=lambda row:int(row[0])):
        if data['masks'][art]['mapID'] == 947:continue
        source=cache/(str(record['fileDataID'])+'.blp')
        if hashlib.sha256(source.read_bytes()).hexdigest() != record['sha256']:
            raise ValueError(f'Native sample hash mismatch: {source}')
        sample=read_texture(source).crop(record['rect'])
        path=output/(art+'.blp')
        save_texture(ocean_field(sample),path)
        generated[art]=hashlib.sha256(path.read_bytes()).hexdigest()
    index.write_text('-- Generated by tools/generate_map_ocean.py; original phase-randomized paper.\n'
                     'local _, NS = ...\nNS.GoldTracker.MapOceanBackdrops = {\n'+
                     ''.join(f'    [{art}] = true,\n' for art in generated)+'}\n')
    data['detail_backdrops']={'algorithm':'native-colour-spectrum-independent-phase-v1','sha256':generated}
    receipt.write_text(json.dumps(data,indent=2)+'\n')
    print(f'Generated {len(generated)} detail backdrops')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--receipt',type=Path,default=Path('docs/research/map-art-masks-2026-10-24.json'))
    parser.add_argument('--cache',type=Path,default=Path('.local/interactive-map-research/textures'))
    parser.add_argument('--output',type=Path,default=Path('UI/Maps/Media/DetailBackdrop'))
    parser.add_argument('--index',type=Path,default=Path('UI/Maps/OceanIndex.lua'))
    args=parser.parse_args()
    generate(args.receipt,args.cache,args.output,args.index)
