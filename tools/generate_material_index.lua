-- Run from the repository root with Lua 5.1 or newer. The index intentionally
-- contains no coordinates, NPC tables or routes, and is safe to load at login.
local ns = {}
assert(loadfile("Data/FarmingItems.lua"))("General-Gold-Tracker", ns)
local root = "Data/General-Gold-Tracker_Materials/"
for line in io.lines(root .. "General-Gold-Tracker_Materials.toc") do
    line = line:gsub("\r", "")
    if line:match("%.lua$") and line ~= "Namespace.lua" then
        assert(loadfile(root .. line))("General-Gold-Tracker", ns)
    end
end

local ids = {}
for id in pairs(ns.MaterialFarmingSpots.items) do
    ids[#ids + 1] = id
end
table.sort(ids)
local function quote(value)
    return string.format("%q", tostring(value))
end
local lines = {
    "local _, NS = ...",
    "-- Generated by tools/generate_material_index.lua; no location data is loaded here.",
    "NS.MaterialIndex = { items = {",
}
for _, id in ipairs(ids) do
    local item = ns.MaterialFarmingSpots.items[id]
    local fields = { "itemID = " .. id }
    for _, key in ipairs({ "itemName", "expansion", "expansionID", "expansionLabel" }) do
        if item[key] ~= nil then
            fields[#fields + 1] = key .. " = " .. quote(item[key])
        end
    end
    if type(item.professions) == "table" then
        local professions = {}
        for _, profession in ipairs(item.professions) do
            professions[#professions + 1] = quote(profession)
        end
        fields[#fields + 1] = "professions = { " .. table.concat(professions, ", ") .. " }"
    end
    fields[#fields + 1] = "hasMap = " .. tostring(type(item.spots) == "table" and #item.spots > 0)
    lines[#lines + 1] = "    [" .. id .. "] = { " .. table.concat(fields, ", ") .. " },"
end
lines[#lines + 1] = "} }"
local output = assert(io.open("Data/MaterialIndex.lua", "wb"))
output:write(table.concat(lines, "\n") .. "\n")
output:close()
print("Generated material index: " .. #ids .. " items")
