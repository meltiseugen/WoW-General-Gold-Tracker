local loader = require("tests.helpers.addon_loader")
local ui = require("tests.helpers.explorer_ui")
local encoding = require("tests.helpers.farm_encoding")

describe("UI/FarmTransferWindow", function()
    it("exports a selected farm or all farms and imports copies through the paste window", function()
        local addon = loader.load_module("Core/CustomFarms.lua", { db = {} })
        loader.load_module("Core/FarmTransfer.lua", addon)
        local _, ns = loader.load_module("UI/FarmTransferWindow.lua", addon, { JanisTheme = {} })
        ui.with_ui(ns, function()
            loader.with_globals({ C_EncodingUtil = encoding.codec }, function()
                local first = addon:CreateCustomFarm("One", false)
                addon:AddEntryToCustomFarm(first.id, { itemID = 2770, x = 0.1, y = 0.2, mapID = 100 })
                addon:CreateCustomFarm("Two", false)
                addon:OpenFarmTransferWindow(first.id)
                local frame = addon.farmTransferFrame
                assert.is_true(frame:IsShown())
                assert.equals(1, #encoding.unwrap(frame.editBox:GetText()).farms)
                assert.is_false(frame.importButton:IsShown())
                frame.exportAllButton.scripts.OnClick()
                local all = frame.editBox:GetText()
                assert.equals(2, #encoding.unwrap(all).farms)
                frame.importModeButton.scripts.OnClick()
                assert.is_true(frame.importButton:IsShown())
                assert.equals("", frame.editBox:GetText())
                assert.is_false(frame.importButton.enabled)
                frame.editBox:SetText("invalid")
                frame.editBox.scripts.OnTextChanged()
                frame.importButton.scripts.OnClick()
                assert.equals(2, #addon:GetCustomFarms())
                assert.matches("Import failed", frame.status:GetText())
                frame.editBox:SetText(all)
                frame.editBox.scripts.OnTextChanged()
                assert.is_true(frame.importButton.enabled)
                frame.importButton.scripts.OnClick()
                assert.equals(4, #addon:GetCustomFarms())
                assert.matches("Imported 2 farms", frame.status:GetText())
                assert.is_false(frame.importButton.enabled)
                frame.editBox.scripts.OnEscapePressed()
                assert.is_false(frame:IsShown())
            end)
        end)
    end)

    it("offers import when there are no farms and keeps export errors visible", function()
        local addon = loader.load_module("Core/CustomFarms.lua", { db = {} })
        loader.load_module("Core/FarmTransfer.lua", addon)
        local _, ns = loader.load_module("UI/FarmTransferWindow.lua", addon, { JanisTheme = {} })
        ui.with_ui(ns, function()
            loader.with_globals({ C_EncodingUtil = {} }, function()
                addon:OpenFarmTransferWindow()
                local frame = addon.farmTransferFrame
                assert.is_true(frame.importMode)
                assert.is_false(frame.exportFarmButton.enabled)
                assert.is_false(frame.exportAllButton.enabled)
                local farm = addon:CreateCustomFarm("One", false)
                addon:OpenFarmTransferWindow(farm.id)
                assert.equals("", frame.editBox:GetText())
                assert.matches("unavailable", frame.status:GetText())
            end)
        end)
    end)
end)
